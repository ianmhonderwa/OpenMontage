#!/usr/bin/env python3
"""Regenerate docs/api_reference.md from the live tool and route definitions."""

from __future__ import annotations

import asyncio
from pathlib import Path

from opensocial.api.app import create_app
from opensocial.core.config import Settings
from opensocial.core.runtime import Runtime
from opensocial.core.security import TokenCipher
from opensocial.servers import core, facebook, instagram, kindle, tiktok, whatsapp, youtube

OUT = Path(__file__).resolve().parents[1] / "docs" / "api_reference.md"


async def tools_section() -> list[str]:
    lines = [
        "## MCP tools",
        "",
        "Every tool returns JSON. Errors are returned as MCP tool errors whose text contains "
        '`{"error": "<code>", "message": "..."}` (codes: `authentication_failed`, `permission_denied`, '
        "`not_found`, `validation_failed`, `emergency_stop_active`, `rate_limited`, `platform_error`, "
        "`token_expired`). Write tools return `status: approval_required` and an `approval_id` until the "
        "owner approves.",
        "",
    ]
    for module in (youtube, tiktok, facebook, instagram, whatsapp, kindle, core):
        server = module.server
        lines += [f"### `{server.name}`", "", server.description or "", ""]
        for tool in await server.list_tools():
            props = tool.input_schema.get("properties", {})
            required = set(tool.input_schema.get("required", []))
            params = ", ".join(f"`{k}`{'' if k in required else '?'}" for k in props) or "—"
            first = (tool.description or "").split("\n\n")[0]
            meta = (tool.description or "").split("\n\n")[-1] if "Operation kind" in (tool.description or "") else ""
            lines += [f"#### `{tool.name}`", "", first, "", f"*Parameters:* {params}", ""]
            if meta:
                lines += [f"*{meta}*", ""]
    return lines


def routes_section() -> list[str]:
    rt = Runtime(Settings(database_url="sqlite://", encryption_keys=TokenCipher.generate_key()))
    schema = create_app(rt).openapi()
    lines = [
        "## REST management API",
        "",
        "Authenticate with `X-API-Key: <key>` or `Authorization: Bearer <key>`. Endpoints marked *owner* "
        "need an owner key; *admin* also needs administrator rights. Interactive docs: `/api/docs`.",
        "",
        "| Method | Path | Summary |",
        "|---|---|---|",
    ]
    for path, methods in sorted(schema["paths"].items()):
        for method, op in methods.items():
            lines.append(f"| {method.upper()} | `{path}` | {op.get('summary', '')} |")
    return [*lines, ""]


def main() -> None:
    body = ["# API reference", "", "_Generated by `scripts/gen_api_reference.py`; do not edit by hand._", ""]
    body += asyncio.run(tools_section()) + routes_section()
    OUT.write_text("\n".join(body))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
